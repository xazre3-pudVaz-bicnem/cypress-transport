import type { PhotoKey } from "./images";

export interface DriverInterview {
  /** URL用のスラッグ */
  slug: string;
  /** 表示名。本名でなくてもよい（例: "Sさん"）が、実在の人物であること */
  name: string;
  /** 属性（例: "30代・前職は飲食"）。本人の同意を得た範囲で */
  attribute: string | null;
  /** 稼働開始時期（例: "2026年10月〜"） */
  startedAt: string | null;
  /** 一覧に出す一言 */
  lead: string;
  /** 質問と回答 */
  qa: { q: string; a: string }[];
  /**
   * 顔写真。本人の同意が取れた実写のみ。
   * イメージ写真を人物写真の代わりに使わないこと。
   */
  photo: PhotoKey | null;
  /** 取材日 */
  interviewedAt: string;
}

